        public static string Node(string name) => nodes.TryGetValue(name, out var value) ? value : name;
        public static string Property(string name) => properties.TryGetValue(name, out var value) ? value : name;
        public static string DisplayNode(string name, bool chinese) => chinese && Node(name) != name ? Node(name) + " / " + name : name;
        public static string DisplayProperty(string name, bool chinese) => chinese && Property(name) != name ? Property(name) + " / " + name : name;
        public static bool Matches(string text, string query) => (query ?? "").Split((char[])null, StringSplitOptions.RemoveEmptyEntries).All(word => text.Contains(word, StringComparison.OrdinalIgnoreCase));
